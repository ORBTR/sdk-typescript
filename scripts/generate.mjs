// Generates src/generated/types.ts and src/generated/resources.ts from contract/orbtr-v1.json.
// Consumes: the contract's components.schemas (objects, enums, arrays, nullable types, oneOf unions and
// discriminated unions) and its paths' x-orbtr-* operation fields. Its output is imported by src/client.ts
// and src/index.ts; test/generated.test.ts regenerates into memory and fails when the files differ.
// Usage: node scripts/generate.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export function generate(contract) {
  return { types: genTypes(contract), resources: genResources(contract) };
}

const HEADER = "// Generated by scripts/generate.mjs from contract/orbtr-v1.json. Do not edit.\n";

function refName(ref) {
  return ref.slice(ref.lastIndexOf("/") + 1);
}

function doc(text, indent = "") {
  if (!text) return "";
  return `${indent}/** ${text.replace(/\*\//g, "* /")} */\n`;
}

function propKey(name) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}

function tsType(s) {
  if (s.$ref) return refName(s.$ref);
  if (s.oneOf) return s.oneOf.map((x) => tsType(x)).join(" | ");
  const types = Array.isArray(s.type) ? s.type : [s.type];
  const parts = types.map((t) => {
    switch (t) {
      case "string":
        return s.enum ? s.enum.map((e) => JSON.stringify(e)).join(" | ") : "string";
      case "integer":
      case "number":
        return "number";
      case "boolean":
        return "boolean";
      case "null":
        return "null";
      case "array": {
        const inner = tsType(s.items);
        return /[| ]/.test(inner) ? `Array<${inner}>` : `${inner}[]`;
      }
      case "object":
        if (s.properties) throw new Error("inline object schemas are not supported");
        return "{ [key: string]: unknown }";
      default:
        if (t === undefined) return "unknown";
        throw new Error(`unsupported type ${t}`);
    }
  });
  return parts.join(" | ");
}

function genTypes(contract) {
  let out = HEADER + "\n";
  for (const [name, s] of Object.entries(contract.components.schemas)) {
    out += doc(s.description);
    if (s.oneOf) {
      out += `export type ${name} =\n${s.oneOf.map((x) => `  | ${tsType(x)}`).join("\n")};\n\n`;
      continue;
    }
    if (s.type !== "object" || !s.properties) throw new Error(`${name}: top-level schemas must be objects or unions`);
    const required = new Set(s.required ?? []);
    out += `export interface ${name} {\n`;
    for (const [p, ps] of Object.entries(s.properties)) {
      out += doc(ps.description, "  ");
      out += `  ${propKey(p)}${required.has(p) ? "" : "?"}: ${tsType(ps)};\n`;
    }
    out += "}\n\n";
  }
  return out.trimEnd() + "\n";
}

function pascal(s) {
  return s
    .split(/[._]/)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
}

function operations(contract) {
  const ops = [];
  for (const [path, item] of Object.entries(contract.paths)) {
    for (const [method, op] of Object.entries(item)) {
      const ok = op.responses["200"].content;
      const [ctype] = Object.keys(ok);
      ops.push({
        path,
        httpMethod: method.toUpperCase(),
        resource: op["x-orbtr-resource"],
        name: op["x-orbtr-method"],
        summary: op.summary,
        scope: op["x-orbtr-scope"],
        idempotencyKey: op["x-orbtr-idempotency-key"] === true,
        stream: op["x-orbtr-stream"],
        body: op.requestBody ? refName(op.requestBody.content["application/json"].schema.$ref) : null,
        response: refName(ok[ctype].schema.$ref),
        ndjson: ctype === "application/x-ndjson",
        pathParams: (op.parameters ?? []).filter((p) => p.in === "path"),
        queryParams: (op.parameters ?? []).filter((p) => p.in === "query"),
      });
    }
  }
  return ops;
}

function streamFlag(contract, bodyName) {
  const s = contract.components.schemas[bodyName];
  return Object.entries(s.properties).find(([, ps]) => ps["x-orbtr-stream-flag"])?.[0];
}

function resourceTree(ops) {
  const tree = new Map();
  for (const op of ops) {
    const segs = op.resource.split(".");
    for (let i = 1; i <= segs.length; i++) {
      const key = segs.slice(0, i).join(".");
      if (!tree.has(key)) tree.set(key, { key, segs: segs.slice(0, i), ops: [], children: [] });
      if (i > 1) {
        const parent = tree.get(segs.slice(0, i - 1).join("."));
        if (!parent.children.includes(key)) parent.children.push(key);
      }
    }
    tree.get(op.resource).ops.push(op);
  }
  return tree;
}

function genResources(contract) {
  const ops = operations(contract);
  const tree = resourceTree(ops);
  const typeNames = new Set();
  let classes = "";
  let queryTypes = "";
  for (const node of [...tree.values()].reverse()) {
    const cls = pascal(node.key);
    let body = "";
    for (const child of node.children) {
      const c = tree.get(child);
      body += `  readonly ${c.segs[c.segs.length - 1]}: ${pascal(child)};\n`;
    }
    body += `${node.children.length ? "\n" : ""}  constructor(client: APIClient) {\n    super(client);\n`;
    for (const child of node.children) {
      const c = tree.get(child);
      body += `    this.${c.segs[c.segs.length - 1]} = new ${pascal(child)}(client);\n`;
    }
    body += "  }\n";
    for (const op of node.ops) {
      typeNames.add(op.response);
      if (op.body) typeNames.add(op.body);
      const args = [];
      for (const p of op.pathParams) args.push(`${p.name}: string`);
      let paramsType = op.body;
      const flag = op.body ? streamFlag(contract, op.body) : undefined;
      if (op.body && flag) paramsType = `Omit<${op.body}, ${JSON.stringify(flag)}>`;
      if (op.body) args.push(`params: ${paramsType}`);
      if (op.queryParams.length) {
        const qt = `${pascal(op.resource)}${pascal(op.name)}Params`;
        queryTypes += doc(`Query parameters of ${op.httpMethod} ${op.path}.`);
        queryTypes += `export interface ${qt} {\n`;
        for (const q of op.queryParams) {
          queryTypes += doc(q.description, "  ") + `  ${propKey(q.name)}?: ${tsType(q.schema)};\n`;
        }
        queryTypes += "}\n\n";
        args.push(`query: ${qt} = {}`);
      }
      args.push("options: RequestOptions = {}");
      const path = op.path.replace(/\{(\w+)\}/g, (_, n) => `\${encodeURIComponent(${n})}`);
      const req = [
        `method: ${JSON.stringify(op.httpMethod)}`,
        `path: \`${path}\``,
      ];
      if (op.queryParams.length) req.push("query: { ...query }");
      if (op.idempotencyKey) req.push("idempotent: true");
      const bodyExpr = (value) => (flag ? `{ ...params, ${flag}: ${value} }` : "params");
      const describe = (summary) => doc(`${summary} ${op.httpMethod} ${op.path}; needs the ${op.scope} scope.`, "  ");
      if (op.ndjson) {
        body += "\n" + describe(op.summary);
        body += `  ${op.name}(${args.join(", ")}): Promise<${op.response}[]> {\n`;
        body += `    return this._client.ndjson<${op.response}>({ ${req.join(", ")} }, options);\n  }\n`;
        continue;
      }
      const createBody = op.body ? [...req, `body: ${flag ? `withoutStream(params, ${JSON.stringify(flag)})` : "params"}`] : req;
      body += "\n" + describe(op.summary);
      body += `  ${op.name}(${args.join(", ")}): Promise<${op.response}> {\n`;
      body += `    return this._client.json<${op.response}>({ ${createBody.join(", ")} }, options);\n  }\n`;
      if (op.stream) {
        const event = refName(op.stream.event);
        const streamReq = [...req, `body: ${bodyExpr("true")}`];
        if (op.stream.framing === "anthropic") {
          body += "\n" + doc(`${op.summary} The reply arrives as server-sent events. ${op.httpMethod} ${op.path} with ${flag}: true; needs the ${op.scope} scope.`, "  ");
          body += `  stream(${args.join(", ")}): Promise<MessageStream> {\n`;
          body += `    return this._client.messageStream({ ${streamReq.join(", ")} }, options);\n  }\n`;
        } else {
          typeNames.add(event);
          body += "\n" + doc(`${op.summary} The reply arrives as server-sent events. ${op.httpMethod} ${op.path} with ${flag}: true; needs the ${op.scope} scope.`, "  ");
          body += `  stream(${args.join(", ")}): Promise<Stream<${event}>> {\n`;
          body += `    return this._client.chunkStream<${event}>({ ${streamReq.join(", ")} }, options);\n  }\n`;
        }
      }
    }
    const paths = [...new Set(node.ops.map((o) => o.path))];
    const classDoc = paths.length ? doc(`The ${paths.join(", ")} routes.`) : doc(`The ${node.key} resources.`);
    classes = `${classDoc}export class ${cls} extends APIResource {\n${body}}\n\n` + classes;
  }
  const roots = [...tree.values()].filter((n) => n.segs.length === 1);
  let out = HEADER;
  out += `import type { APIClient, RequestOptions } from "../core.js";\n`;
  out += `import { APIResource, withoutStream } from "../core.js";\n`;
  out += `import type { MessageStream, Stream } from "../streaming.js";\n`;
  out += `import type {\n${[...typeNames].sort().map((t) => `  ${t},`).join("\n")}\n} from "./types.js";\n\n`;
  out += queryTypes;
  out += classes;
  out += doc("The API's resources, one per top-level path segment.");
  out += `export interface Resources {\n${roots.map((r) => `  readonly ${r.key}: ${pascal(r.key)};`).join("\n")}\n}\n\n`;
  out += doc("Builds every resource over one client.");
  out += `export function createResources(client: APIClient): Resources {\n  return {\n${roots
    .map((r) => `    ${r.key}: new ${pascal(r.key)}(client),`)
    .join("\n")}\n  };\n}\n`;
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const contract = JSON.parse(readFileSync(join(root, "contract/orbtr-v1.json"), "utf8"));
  const out = generate(contract);
  const files = { "src/generated/types.ts": out.types, "src/generated/resources.ts": out.resources };
  let stale = false;
  for (const [rel, text] of Object.entries(files)) {
    const path = join(root, rel);
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current === text) continue;
    if (process.argv.includes("--check")) {
      console.error(`${rel} is not what contract/orbtr-v1.json generates; run npm run generate`);
      stale = true;
    } else {
      writeFileSync(path, text);
      console.log(`wrote ${rel}`);
    }
  }
  if (stale) process.exit(1);
}
